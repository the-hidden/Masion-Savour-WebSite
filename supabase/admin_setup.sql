-- Mansion Savour · Panel de administración del menú
-- Seguridad de la tabla public.menu con Supabase Auth + RLS
--
-- Cómo usarlo: Supabase -> SQL Editor -> New query -> pegar TODO -> Run.
-- Es seguro ejecutarlo más de una vez (no duplica ni borra datos).
--
-- Reglas que deja configuradas:
--   * El público (visitantes de la web) solo puede LEER los platos disponibles.
--   * Solo los EMPLEADOS pueden ver todos los platos, crear, editar y borrar.
--   * "Empleado" = usuario cuyo app_metadata tiene role = 'empleado'.
--     app_metadata solo lo puede cambiar el administrador (SQL Editor o
--     service_role); un usuario NO puede ponérselo a sí mismo.
--
-- Nota sobre el nombre: se usa la tabla "menu" porque es la que ya lee tu
-- página pública. Si prefieres llamarla "platos", ejecuta antes:
--     alter table public.menu rename to platos;
-- y cambia SUPABASE_MENU_TABLE en src/Config.js (y reemplaza "public.menu" aquí).
-- =====================================================================


-- 1) Tabla (si ya existe, esta parte no hace nada) ---------------------
create table if not exists public.menu (
    id           bigint generated by default as identity primary key,
    categoria    text    not null,                      -- Desayuno, Almuerzo, Cena, Postres & Jugos, Cafes
    nombre       text    not null,
    tiempo       text,                                  -- ej: '10 min'
    precio       numeric(8,2) not null default 0 check (precio >= 0),
    favorito     boolean not null default false,
    descripcion  text,
    imagen       text,                                  -- URL de la imagen
    disponible   boolean not null default true,         -- false = oculto en la web pública
    created_at   timestamptz not null default now()
);


-- 2) Función: ¿el usuario actual es empleado? --------------------------
create or replace function public.es_empleado()
returns boolean
language sql
stable
as $$
    select coalesce((auth.jwt() -> 'app_metadata' ->> 'role') = 'empleado', false);
$$;


-- 3) Permisos de tabla (qué rol puede intentar qué) --------------------
grant select                         on public.menu to anon;
grant select, insert, update, delete on public.menu to authenticated;


-- 4) Row Level Security: quién puede ver/modificar qué FILAS -----------
alter table public.menu enable row level security;

-- Limpia políticas anteriores (incluida la del primer script) para no acumularlas.
drop policy if exists "Menu visible para todos"     on public.menu;
drop policy if exists "Empleados ven todo"          on public.menu;
drop policy if exists "Empleados insertan platos"   on public.menu;
drop policy if exists "Empleados editan platos"     on public.menu;
drop policy if exists "Empleados borran platos"     on public.menu;

-- Público: solo platos disponibles (esto es lo que usa la web).
create policy "Menu visible para todos"
    on public.menu for select
    to anon, authenticated
    using (disponible = true);

-- Empleados: ven TODO (también los platos no disponibles, para poder reactivarlos).
create policy "Empleados ven todo"
    on public.menu for select
    to authenticated
    using ((select public.es_empleado()));

create policy "Empleados insertan platos"
    on public.menu for insert
    to authenticated
    with check ((select public.es_empleado()));

create policy "Empleados editan platos"
    on public.menu for update
    to authenticated
    using ((select public.es_empleado()))
    with check ((select public.es_empleado()));

create policy "Empleados borran platos"
    on public.menu for delete
    to authenticated
    using ((select public.es_empleado()));


